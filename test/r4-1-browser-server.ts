import cookieParser from 'cookie-parser';
import express from 'express';
import { createServer } from 'node:http';
import { initSocketServer } from '../src/services/socket.ts';
import { registerRoutes } from '../src/routes/index.ts';
import { users, quizzes, results, aiJobs } from '../src/store/db.ts';
import { createSessionToken } from '../src/middleware/auth.ts';
import { configureGeminiClientForTests } from '../src/services/gemini.ts';
import { mockQuestion, tutorialProvider, syntheticPdf } from './r4-1-fixtures.ts';
users.clear();quizzes.clear();results.clear();aiJobs.clear();
const provider=tutorialProvider(300);configureGeminiClientForTests(()=>provider.client);
const teacher={uid:'tutorial_teacher',name:'Synthetic Teacher',email:'teacher@example.invalid',role:'teacher',stored_custom_key:'synthetic-key'} as any;
users.set(teacher.uid,teacher);
const students=Array.from({length:4},(_,i)=>({uid:'tutorial_student_'+i,name:'Synthetic Student '+i,email:`student${i}@example.invalid`,role:'student'} as any));students.forEach(s=>users.set(s.uid,s));
quizzes.set('tutorial',{id:'tutorial',user_id:teacher.uid,title:'Synthetic live tutorial',subject:'English',quiz_mode:'back_and_forth',time_limit:200,questions:[...Array.from({length:11},(_,i)=>mockQuestion(String(i+1))),{id:'12',question:'Explain your claim.',type:'open_ended',answer:'A justified claim.',points:2}]});
const app=express();app.use(cookieParser());app.set('view engine','ejs');app.use(express.json({limit:'30mb'}));app.use(express.urlencoded({extended:true}));app.use(express.static('public'));
app.get('/__fixtures',(_req,res)=>res.json({teacher:createSessionToken(teacher,600_000),students:students.map(s=>createSessionToken(s,600_000))}));
app.get('/__worksheet',(_req,res)=>res.type('application/pdf').send(syntheticPdf()));
app.get('/__metrics',(_req,res)=>res.json({calls:provider.calls,page_calls:provider.pageCalls}));
registerRoutes(app);app.use((error:any,_req:any,res:any,_next:any)=>res.status(error.status || 500).json({error:'Synthetic fixture request failed'}));
const server=createServer(app);const io=initSocketServer(server);app.set('io',io);
server.listen(3000,'127.0.0.1',()=>console.log('R4.1 synthetic server ready'));
process.on('SIGTERM',()=>{io.close();server.close();});
